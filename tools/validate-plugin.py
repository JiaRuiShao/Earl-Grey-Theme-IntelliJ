"""Checks a built Earl Grey UI Theme jar before it is released, or the "Earl Grey.icls" users import directly.

    python3 tools/validate-plugin.py build/EarlGreyTheme-1.2.0.jar [expected-version]
    python3 tools/validate-plugin.py --icls "Earl Grey.icls"

Fails (exit 1) when:
  * plugin.xml is malformed, has the wrong id, or a version other than the expected one;
  * the theme JSON's editorScheme or any icon it maps is missing from the jar;
  * the jar's editor scheme is not named "EarlGrey" (the name published releases use; users' selection is stored
    under it), or the .icls is not named "Earl Grey" with parent_scheme "Default";
  * the scheme carries an "originalScheme" or "partialSave" property, whatever its value. originalScheme makes an
    imported copy borrow the label of the read-only scheme it names (a lookalike duplicate in Settings), and
    IntelliJ's own Export writes it, so it comes back whenever the .icls is regenerated by Export; partialSave
    hides the scheme when that original is missing;
  * the scheme uses an attributes key IntelliJ does not define (1.1.0 shipped 14 such keys, so those Java
    elements silently fell back to other colors) - see tools/intellij-keys.txt - or defines a key twice;
  * the Parity license text is missing (the license requires every copy to carry it).
"""
import json
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

PLUGIN_ID = "wtf.halt.earlgrey.theme"
SCHEME_NAME = "EarlGrey"
ICLS_SCHEME_NAME = "Earl Grey"
FORBIDDEN_META = ("originalScheme", "partialSave")


def known_keys():
    return {line.strip() for line in (Path(__file__).parent / "intellij-keys.txt").read_text().splitlines()
            if line.strip() and not line.startswith("#")}


def check_scheme(scheme, expected_name, errors):
    """Checks shared by the jar's EarlGrey.xml and Earl Grey.icls; returns the number of attributes keys."""
    if scheme.get("name") != expected_name:
        errors.append("scheme name is %r, expected %r" % (scheme.get("name"), expected_name))
    meta = scheme.find("metaInfo")
    for prop in meta if meta is not None else []:
        if prop.get("name") in FORBIDDEN_META:
            errors.append("scheme has a %r property (%r)" % (prop.get("name"), prop.text))
    attributes = [o.get("name") for o in scheme.find("attributes")]
    known = known_keys()
    unknown = [k for k in attributes if k not in known]
    if unknown:
        errors.append("unknown attributes keys (IntelliJ ignores them): %s" % ", ".join(unknown))
    duplicated = sorted({k for k in attributes if attributes.count(k) > 1})
    if duplicated:
        errors.append("keys defined twice: %s" % ", ".join(duplicated))
    return len(attributes)


def validate_icls(path, errors):
    scheme = ET.parse(path).getroot()
    if scheme.get("parent_scheme") != "Default":
        errors.append("parent_scheme is %r, expected 'Default'" % scheme.get("parent_scheme"))
    count = check_scheme(scheme, ICLS_SCHEME_NAME, errors)
    return "scheme %s, %d keys" % (ICLS_SCHEME_NAME, count)


def validate_jar(jar_path, expected_version, errors):
    jar = zipfile.ZipFile(jar_path)
    names = set(jar.namelist())

    plugin = ET.fromstring(jar.read("META-INF/plugin.xml"))
    if plugin.findtext("id") != PLUGIN_ID:
        errors.append("plugin id is %r, expected %r" % (plugin.findtext("id"), PLUGIN_ID))
    version = plugin.findtext("version")
    if expected_version and version != expected_version:
        errors.append("plugin version is %r, expected %r" % (version, expected_version))
    providers = plugin.findall("extensions/themeProvider")
    if len(providers) != 1:
        errors.append("expected exactly one themeProvider, found %d" % len(providers))
    if plugin.findall("extensions/bundledColorScheme"):
        errors.append("bundledColorScheme registers the scheme a second time (the theme JSON already does)")
    if "META-INF/LICENSE-PARITY.md" not in names:
        errors.append("META-INF/LICENSE-PARITY.md is missing")

    theme_path = providers[0].get("path").lstrip("/") if providers else ""
    theme = json.loads(jar.read(theme_path))
    scheme_path = theme.get("editorScheme", "").lstrip("/")
    if scheme_path not in names:
        errors.append("editorScheme %r is not in the jar" % scheme_path)

    def icon_targets(node):
        if isinstance(node, dict):
            for k, v in node.items():
                if k == "ColorPalette":
                    continue
                if isinstance(v, str) and v.endswith(".svg"):
                    yield v
                else:
                    yield from icon_targets(v)
    for target in sorted(set(icon_targets(theme.get("icons", {})))):
        if target.lstrip("/") not in names:
            errors.append("icon %s mapped in the theme JSON is not in the jar" % target)

    count = 0
    if scheme_path in names:
        count = check_scheme(ET.fromstring(jar.read(scheme_path)), SCHEME_NAME, errors)
    return "version %s, scheme %s, %d keys" % (version, SCHEME_NAME, count)


def main():
    errors = []
    if sys.argv[1] == "--icls":
        path = sys.argv[2]
        summary = validate_icls(path, errors)
    else:
        path = sys.argv[1]
        summary = validate_jar(path, sys.argv[2] if len(sys.argv) > 2 else None, errors)
    if errors:
        print("INVALID %s" % path)
        for e in errors:
            print("  - " + e)
        sys.exit(1)
    print("OK %s (%s)" % (path, summary))


if __name__ == "__main__":
    main()
